const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const skills = require('../bin/custom-skills')
function fixture(t, name = 'my-skill') {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'product-os-custom-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const workspace = path.join(directory, 'product'), source = path.join(directory, name)
  fs.mkdirSync(workspace); fs.mkdirSync(source)
  fs.writeFileSync(path.join(source, 'SKILL.md'), `---\nname: ${name}\ndescription: Help with a specific task.\n---\n\nUse PRODUCT.md and graph-write.\n`)
  return { directory, workspace, source, name }
}
test('custom skills install for both agents, preserve executable scripts and share a canonical source', t => {
  const { workspace, source } = fixture(t)
  fs.mkdirSync(path.join(source, 'scripts')); fs.writeFileSync(path.join(source, 'scripts/run.sh'), '#!/bin/sh\nexit 1\n', { mode: 0o755 })
  const result = skills.add(workspace, source)
  for (const base of ['.agents', '.claude']) {
    const installed = path.join(workspace, base, 'skills/my-skill')
    assert.equal(skills.readSkill(installed).revision, result.revision)
    assert.ok(fs.statSync(path.join(installed, 'scripts/run.sh')).mode & 0o111)
  }
  assert.equal(result.verified, false)
  assert.equal(skills.list(workspace)[0].source, result.source)
  fs.appendFileSync(path.join(result.source, 'SKILL.md'), '\nA new behavior.\n')
  assert.equal(skills.list(workspace)[0].changed, true)
  assert.throws(() => skills.verify(workspace, 'my-skill', 'A real example'), /skills sync/)
  skills.add(workspace, result.source)
  assert.equal(skills.list(workspace)[0].changed, false)
})
test('a conflict at either agent prevents all changes and preserves independent edits', t => {
  const { workspace, source } = fixture(t)
  const first = skills.add(workspace, source)
  const codex = path.join(workspace, '.agents/skills/my-skill/SKILL.md')
  const claude = path.join(workspace, '.claude/skills/my-skill/SKILL.md')
  fs.appendFileSync(codex, '\nPersonal edit.\n')
  fs.appendFileSync(path.join(first.source, 'SKILL.md'), '\nSource edit.\n')
  const before = fs.readFileSync(claude, 'utf8')
  assert.throws(() => skills.add(workspace, first.source), /изменённый/)
  assert.equal(fs.readFileSync(claude, 'utf8'), before)
  assert.match(fs.readFileSync(codex, 'utf8'), /Personal edit/)
})
test('unmanaged skills, bundled names, hidden files and links cannot be overwritten or imported', t => {
  const { workspace, source, directory } = fixture(t)
  const destination = path.join(workspace, '.claude/skills/my-skill')
  fs.mkdirSync(path.dirname(destination), { recursive: true }); fs.cpSync(source, destination, { recursive: true })
  assert.throws(() => skills.add(workspace, source), /отдельный/)
  assert.equal(fs.existsSync(path.join(workspace, '.agents/skills/my-skill')), false)
  fs.writeFileSync(path.join(source, '.env'), 'PRIVATE')
  assert.throws(() => skills.readSkill(source), /скрытые/)
  fs.unlinkSync(path.join(source, '.env'))
  fs.symlinkSync(path.join(directory, 'missing'), path.join(source, 'references'))
  assert.throws(() => skills.readSkill(source), /обычные файлы/)
  const bundled = path.join(directory, 'product-context'); fs.mkdirSync(bundled)
  fs.writeFileSync(path.join(bundled, 'SKILL.md'), '---\nname: product-context\ndescription: Existing skill.\n---\n')
  assert.throws(() => skills.add(workspace, bundled), /поставляемого/)
})
test('sharing is offered only after actual reported verification, once per revision, with refusal remembered', t => {
  const { workspace, source } = fixture(t), result = skills.add(workspace, source)
  assert.equal(skills.offer(workspace, 'my-skill').shouldAsk, false)
  assert.throws(() => skills.verify(workspace, 'my-skill', ''), /evidence/)
  skills.verify(workspace, 'my-skill', 'A fictional example produced the expected result.')
  assert.equal(skills.offer(workspace, 'my-skill').shouldAsk, true)
  assert.equal(skills.offer(workspace, 'my-skill').shouldAsk, false)
  skills.offer(workspace, 'my-skill', { decline: true })
  skills.add(workspace, result.source)
  assert.equal(skills.offer(workspace, 'my-skill').shouldAsk, false)
  fs.appendFileSync(path.join(result.source, 'SKILL.md'), '\nDifferent behavior.\n')
  skills.add(workspace, result.source)
  assert.equal(skills.offer(workspace, 'my-skill').shouldAsk, false)
  skills.verify(workspace, 'my-skill', 'Rechecked the changed behavior.')
  assert.equal(skills.offer(workspace, 'my-skill').shouldAsk, true)
})
test('PR preparation includes only selected files and explicit attribution, and never publishes', t => {
  const { workspace, source } = fixture(t)
  fs.mkdirSync(path.join(source, 'references')); fs.writeFileSync(path.join(source, 'references/example.md'), 'Fictional example.')
  fs.mkdirSync(path.join(workspace, 'sources')); fs.writeFileSync(path.join(workspace, 'sources/private.md'), 'Private material')
  skills.add(workspace, source)
  assert.throws(() => skills.prepare(workspace, 'my-skill', { author: 'Contributor' }), /проверьте/)
  skills.verify(workspace, 'my-skill', 'Tested a fictional example.')
  const first = skills.prepare(workspace, 'my-skill', { author: 'Contributor' })
  assert.deepEqual(first.files, ['AUTHOR.md', 'SKILL.md'])
  assert.deepEqual(first.omitted, ['references/example.md'])
  assert.equal(first.submitted, false)
  const result = skills.prepare(workspace, 'my-skill', { author: 'Contributor', files: ['references/example.md'] })
  assert.deepEqual(result.files, ['AUTHOR.md', 'SKILL.md', 'references/example.md'])
  assert.match(fs.readFileSync(path.join(result.directory, 'community-skills/my-skill/AUTHOR.md'), 'utf8'), /Contributor/)
  assert.equal(fs.readFileSync(result.bodyFile, 'utf8').includes('Private material'), false)
  assert.equal(fs.existsSync(path.join(result.directory, '.git')), false)
  assert.throws(() => skills.prepare(workspace, 'my-skill', { author: 'Contributor', files: ['../../sources/private.md'] }), /не входит/)
})
test('symlinked agent and state directories are refused before mutation', t => {
  const { workspace, source, directory } = fixture(t)
  const outside = path.join(directory, 'outside'); fs.mkdirSync(outside)
  fs.symlinkSync(outside, path.join(workspace, '.agents'))
  assert.throws(() => skills.add(workspace, source), /Символические/)
  assert.deepEqual(fs.readdirSync(outside), [])
  fs.unlinkSync(path.join(workspace, '.agents'))
  fs.symlinkSync(outside, path.join(workspace, '.product-os'))
  assert.throws(() => skills.add(workspace, source), /Символические/)
})
test('standalone CLI accepts custom skills and unknown options fail without changes', t => {
  const { workspace, source } = fixture(t), cli = path.resolve(__dirname, '../bin/product-os.js')
  assert.throws(() => execFileSync(process.execPath, [cli, 'skills', 'add', workspace, source, '--unknown', 'value'], { stdio: 'pipe' }))
  assert.equal(fs.existsSync(path.join(workspace, '.product-os')), false)
  const result = JSON.parse(execFileSync(process.execPath, [cli, 'skills', 'add', workspace, source, '--agent', 'codex'], { encoding: 'utf8' }))
  assert.deepEqual(result.agents, ['codex'])
})
